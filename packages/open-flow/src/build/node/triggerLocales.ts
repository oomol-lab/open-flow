import type { Plugin } from 'vite'

import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { uiLanguages } from '../../localization/common/languages.ts'

const providersRoot = path.resolve(import.meta.dirname, '../../trigger/providers')

/** Generate bundler-visible imports from provider-owned JSON resources. */
export async function generateTriggerLocales(root: string = providersRoot, check = false): Promise<void> {
  const providers = (await readdir(root, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .toSorted()
  const resources = new Map<string, string[]>()
  for (const provider of providers) {
    let files: string[]
    try {
      files = await readdir(path.join(root, provider, 'locales'))
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code == 'ENOENT') continue
      throw error
    }
    for (const locale of uiLanguages) {
      if (locale == 'en' || !files.includes(`${locale}.json`)) continue
      const entries = resources.get(locale) ?? []
      entries.push(provider)
      resources.set(locale, entries)
    }
  }
  const output = path.join(root, 'locales')
  if (!check) await mkdir(output, { recursive: true })
  for (const locale of uiLanguages) {
    if (locale == 'en') continue
    const entries = resources.get(locale) ?? []
    const imports = entries.map((provider, index) => `import resource${index} from '../${provider}/locales/${locale}.json' with { type: 'json' }`)
    const content = `// Generated by trigger-locales.ts. Do not edit; update provider locales/*.json instead.\n\n${imports.join('\n')}\n\nexport default {${entries.length == 0 ? '' : '\n' + entries.map((_, index) => `  ...resource${index},`).join('\n') + '\n'}}\n`
    const target = path.join(output, `${locale}.ts`)
    let current: string | undefined
    try {
      current = await readFile(target, 'utf8')
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code != 'ENOENT') throw error
    }
    if (current == content) continue
    if (check) throw new Error(`Trigger locale index is stale: ${target}. Run bun run --cwd packages/open-flow generate:trigger-locales.`)
    await writeFile(target, content)
  }
}

/** Refresh indexes at startup and when provider resource files are added or removed. */
export function triggerLocalesPlugin(): Plugin {
  return {
    name: 'open-flow-trigger-locales',
    async configResolved() {
      await generateTriggerLocales()
    },
    configureServer(server) {
      let pending = Promise.resolve()
      const changed = (file: string): void => {
        if (!/^[^/]+\/locales\/[^/]+\.json$/.test(path.relative(providersRoot, file).split(path.sep).join('/'))) return
        pending = pending.then(() => generateTriggerLocales()).catch((error: unknown) => server.config.logger.error(String(error)))
      }
      server.watcher.add(providersRoot)
      server.watcher.on('add', changed)
      server.watcher.on('unlink', changed)
      server.httpServer?.once('close', () => {
        server.watcher.off('add', changed)
        server.watcher.off('unlink', changed)
      })
    },
  }
}
